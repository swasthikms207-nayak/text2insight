import os
import re
import json
import requests
import pandas as pd
from typing import Dict, Any, Tuple, Optional
from .safety import clean_code_block

SYSTEM_PROMPT = """You are an expert Data Analyst and Code Generator.
Given a dataset schema and a natural language question, your task is to generate safe, read-only SQL or Pandas code.

Rules:
1. Always generate READ-ONLY code. Never generate INSERT, UPDATE, DELETE, DROP, ALTER, etc.
2. In SQL mode:
   - The table is named `df` (or `dataset`).
   - Use standard ANSI SQL supported by DuckDB / PostgreSQL.
   - Return clean SQL without comments or extra explanations.
3. In Pandas mode:
   - The input DataFrame is named `df`.
   - Assign the final computed DataFrame or Series to `result_df`.
   - Never import forbidden modules (os, sys, subprocess, etc.). Never write files.
4. Output JSON strictly adhering to this format:
{
  "code": "<only SQL or Python code>",
  "code_type": "sql" or "pandas",
  "reasoning": "<1-2 sentence explanation of logic>"
}
"""

def parse_llm_json_response(
    content: str,
    provider_label: str,
    model_label: str,
    default_mode: str = "sql"
) -> Tuple[str, str, str]:
    """Robustly extracts code, code_type, and reasoning from raw LLM output,
    stripping markdown fences (```sql, ```python, ```json, etc.)."""
    raw = content.strip()
    
    # Strip enclosing markdown code fences
    if raw.startswith("```"):
        lines = raw.split("\n")
        if lines[0].startswith("```"):
            lines = lines[1:]
        if lines and lines[-1].strip().startswith("```"):
            lines = lines[:-1]
        raw = "\n".join(lines).strip()

    parsed = None
    try:
        parsed = json.loads(raw)
    except Exception:
        # Regex search for the outermost JSON block
        m = re.search(r"\{.*\}", content, re.DOTALL)
        if m:
            try:
                parsed = json.loads(m.group(0))
            except Exception:
                pass

    if isinstance(parsed, dict) and "code" in parsed:
        code = clean_code_block(str(parsed["code"]))
        code_type = str(parsed.get("code_type", default_mode)).lower()
        if code_type not in ["sql", "pandas"]:
            code_type = "pandas" if "result_df" in code else "sql"
        reasoning = str(parsed.get("reasoning", f"Generated by {provider_label} ({model_label})"))
        return code, code_type, reasoning

    # Fallback if model returned raw code directly instead of JSON
    cleaned = clean_code_block(content)
    code_type = "pandas" if ("result_df" in cleaned or "df[" in cleaned) and "SELECT " not in cleaned.upper() else "sql"
    return cleaned, code_type, f"Generated by {provider_label} ({model_label})"


def _build_schema_prompt(df: pd.DataFrame, question: str, mode: str) -> str:
    """Formats the DataFrame schema and question for LLM prompts."""
    schema_info = []
    for col in df.columns:
        sample_vals = df[col].dropna().head(3).tolist()
        dtype = str(df[col].dtype)
        schema_info.append(f"- Column: `{col}` ({dtype}), sample values: {sample_vals}")
    schema_text = "\n".join(schema_info)

    target_lang = mode.upper() if mode in ['sql', 'pandas'] else 'SQL'
    return f"""Dataset Table: `df`
Total Rows: {len(df)}
Columns and Sample Data:
{schema_text}

Target Language: {target_lang}
User Question: "{question}"

Generate clean, efficient, safe {target_lang} code that directly answers the user's question.
Remember:
- In SQL: read-only query over table `df`.
- In Pandas: assign output to `result_df`. No imports.
- Respond ONLY with a valid JSON object matching:
{{"code": "<code string>", "code_type": "{mode if mode in ['sql', 'pandas'] else 'sql'}", "reasoning": "<explanation>"}}
"""


from dotenv import load_dotenv

# Load server environment variables
load_dotenv()

BACKEND_DEFAULT_GROQ_KEY = os.getenv("GROQ_API_KEY", "")
BACKEND_DEFAULT_GEMINI_KEY = os.getenv("GEMINI_API_KEY", "")


def generate_with_gemini(
    question: str,
    df: pd.DataFrame,
    mode: str,
    api_key: str,
    model_name: Optional[str] = "gemini-3.8-flash"
) -> Tuple[str, str, str]:
    """Generates SQL or Pandas code using Google Gemini API."""
    from google import genai
    from google.genai import types

    chosen_model = model_name or "gemini-3.8-flash"
    prompt = _build_schema_prompt(df, question, mode)

    try:
        client = genai.Client(api_key=api_key)
        try:
            response = client.models.generate_content(
                model=chosen_model,
                contents=prompt,
                config=types.GenerateContentConfig(
                    system_instruction=SYSTEM_PROMPT,
                    response_mime_type="application/json"
                )
            )
        except Exception as inner_e:
            # If primary model is experiencing high demand (503), automatically fall back to gemini-3.5-flash-lite
            if "503" in str(inner_e) and chosen_model != "gemini-3.5-flash-lite":
                chosen_model = "gemini-3.5-flash-lite"
                response = client.models.generate_content(
                    model=chosen_model,
                    contents=prompt,
                    config=types.GenerateContentConfig(
                        system_instruction=SYSTEM_PROMPT,
                        response_mime_type="application/json"
                    )
                )
            else:
                raise
        return parse_llm_json_response(response.text, "Google Gemini", chosen_model, mode)
    except Exception as e:
        raise RuntimeError(f"Google Gemini Error ({chosen_model}): {str(e)}")


def generate_with_groq(
    question: str,
    df: pd.DataFrame,
    mode: str,
    api_key: str,
    model_name: Optional[str] = "openai/gpt-oss-120b"
) -> Tuple[str, str, str]:
    """Generates SQL or Pandas code using Groq API with ultra-low latency LPU inference."""
    chosen_model = model_name or "openai/gpt-oss-120b"

    # Automatically map deprecated model IDs if user had them saved
    if chosen_model in ["llama-3.3-70b-versatile", "llama-3.1-8b-instant"]:
        chosen_model = "openai/gpt-oss-120b"
    elif chosen_model in ["qwen-2.5-coder-32b", "qwen-2.5-32b"]:
        chosen_model = "qwen/qwen3.8-27b"

    prompt = _build_schema_prompt(df, question, mode)

    headers = {
        "Authorization": f"Bearer {api_key}",
        "Content-Type": "application/json"
    }
    payload = {
        "model": chosen_model,
        "messages": [
            {"role": "system", "content": SYSTEM_PROMPT},
            {"role": "user", "content": prompt}
        ],
        "response_format": {"type": "json_object"}
    }

    try:
        resp = requests.post("https://api.groq.com/openai/v1/chat/completions", headers=headers, json=payload, timeout=25.0)
        if resp.status_code != 200:
            err_detail = resp.text
            try:
                err_detail = resp.json().get("error", {}).get("message", resp.text)
            except Exception:
                pass
            raise RuntimeError(f"Groq API Error ({resp.status_code}): {err_detail}")
        
        data = resp.json()
        content = data["choices"][0]["message"]["content"]
        return parse_llm_json_response(content, "Groq LPU", chosen_model, mode)
    except Exception as e:
        if isinstance(e, RuntimeError):
            raise
        raise RuntimeError(f"Groq API Connection Error ({chosen_model}): {str(e)}")


def generate_with_local_ollama(
    question: str,
    df: pd.DataFrame,
    mode: str,
    base_url: Optional[str] = None,
    model_name: Optional[str] = "text2insight-qwen"
) -> Tuple[str, str, str]:
    """Generates SQL or Pandas code using a local Ollama instance (e.g. QLoRA fine-tuned Qwen)."""
    chosen_model = model_name or "text2insight-qwen"
    raw_url = (base_url or "http://localhost:11434/v1").strip().rstrip("/")
    if not raw_url.endswith("/v1"):
        endpoint = f"{raw_url}/v1/chat/completions"
    else:
        endpoint = f"{raw_url}/chat/completions"

    prompt = _build_schema_prompt(df, question, mode)

    headers = {
        "Authorization": "Bearer ollama",
        "Content-Type": "application/json"
    }
    payload = {
        "model": chosen_model,
        "messages": [
            {"role": "system", "content": SYSTEM_PROMPT},
            {"role": "user", "content": prompt}
        ],
        "temperature": 0
    }

    try:
        resp = requests.post(endpoint, headers=headers, json=payload, timeout=60.0)
        if resp.status_code == 404:
            raise RuntimeError(
                f"Model '{chosen_model}' was not found in local Ollama. "
                f"Verify the model is installed with `ollama list` or pull it using `ollama pull {chosen_model}`."
            )
        elif resp.status_code != 200:
            err_detail = resp.text
            try:
                err_detail = resp.json().get("error", {}).get("message", resp.text)
            except Exception:
                pass
            raise RuntimeError(f"Local Ollama Error ({resp.status_code}): {err_detail}")

        data = resp.json()
        content = data["choices"][0]["message"]["content"]
        return parse_llm_json_response(content, "Local Qwen Ollama", chosen_model, mode)
    except requests.exceptions.ConnectionError:
        raise RuntimeError(
            f"Cannot connect to local Ollama at '{endpoint}'. "
            "Please ensure Ollama is running (`ollama serve`)."
        )
    except Exception as e:
        if isinstance(e, RuntimeError):
            raise
        raise RuntimeError(f"Local Ollama Execution Error ({chosen_model}): {str(e)}")


def generate_code_and_reasoning(
    question: str,
    df: pd.DataFrame,
    mode: str = "auto",
    provider: str = "groq",
    api_key: Optional[str] = None,
    model_name: Optional[str] = None,
    base_url: Optional[str] = None
) -> Tuple[str, str, str]:
    """Master entry point for NL -> Code generation across LLM providers (Gemini, Groq, and Local Qwen Ollama)."""
    selected_provider = (provider or "groq").lower().strip()
    gemini_key = api_key or os.getenv("GEMINI_API_KEY") or BACKEND_DEFAULT_GEMINI_KEY
    groq_key = api_key or os.getenv("GROQ_API_KEY") or BACKEND_DEFAULT_GROQ_KEY

    # 1. Google Gemini
    if selected_provider == "gemini":
        if not gemini_key:
            raise RuntimeError("Google Gemini API Key is required. Please configure it in LLM Engine Settings.")
        return generate_with_gemini(question, df, mode, gemini_key, model_name)

    # 2. Groq LPU (Default)
    if selected_provider in ["groq", "openai", "default"]:
        key = groq_key or api_key
        if not key:
            raise RuntimeError("Groq API Key (gsk_...) is required. Please configure it in LLM Engine Settings.")
        return generate_with_groq(question, df, mode, key, model_name)

    # 3. Local Qwen (Ollama / QLoRA)
    if selected_provider == "local_ollama":
        return generate_with_local_ollama(question, df, mode, base_url, model_name)

    if selected_provider == "qwen":
        raise RuntimeError("Qwen Cloud has been removed. Please select Groq LPU or Local Qwen (Ollama).")

    if selected_provider in ["smart-local", "builtin", "local"]:
        # Seamlessly fallback to pre-configured Groq LPU
        return generate_with_groq(question, df, mode, groq_key, model_name)

    raise RuntimeError(f"Unknown LLM provider '{provider}'. Please select Groq LPU, Gemini, or Local Qwen (Ollama).")
